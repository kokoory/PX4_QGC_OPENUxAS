class BridgeCLI(cmd.Cmd):
    intro = textwrap.dedent("""
        QGC <-> OpenUxAS Bridge CLI
        Type 'help' for available commands.
    """)
    prompt = "bridge> "

    def __init__(self, bridge: QGCUxASBridge):
        super().__init__()
        self.bridge = bridge

    def do_register(self, arg: str) -> None:
        """Register the vehicle with UxAS (sends AirVehicleConfiguration)."""
        self.bridge.register_vehicle()

    def do_area_search(self, arg: str) -> None:
        """area_search lat1,lon1 lat2,lon2 lat3,lon3 [lat4,lon4 ...] [alt]"""
        area, alt = self._parse_points_and_alt(arg, min_points=3)
        if area is None:
            return
        tid = self.bridge.send_area_search(area, altitude=alt)
        print(f"AreaSearch task {tid} submitted")

    def do_line_search(self, arg: str) -> None:
        """line_search lat1,lon1 lat2,lon2 [lat3,lon3 ...] [alt]"""
        pts, alt = self._parse_points_and_alt(arg, min_points=2)
        if pts is None:
            return
        tid = self.bridge.send_line_search(pts, altitude=alt)
        print(f"LineSearch task {tid} submitted")

    def do_status(self, arg: str) -> None:
        """Show bridge status, message counters, vehicle state."""
        print(json.dumps(self.bridge.get_status(), indent=2))

    def do_state(self, arg: str) -> None:
        """Show current vehicle state."""
        s = self.bridge.mavlink.get_state()
        info = {
            "vehicle_id": s.vehicle_id,
            "position": f"({s.lat_deg:.7f}, {s.lon_deg:.7f})",
            "altitude_m": f"{s.alt_m:.1f}",
            "heading_deg": f"{s.heading_deg:.1f}",
            "airspeed_mps": f"{s.airspeed_mps:.1f}",
            "groundspeed_mps": f"{s.groundspeed_mps:.1f}",
            "mode": s.mode, "armed": s.armed,
            "battery_pct": f"{s.battery_pct:.0f}",
        }
        for k, v in info.items():
            print(f"  {k:18s}: {v}")

    def do_messages(self, arg: str) -> None:
        """Show recent LMCP message types received from UxAS."""
        n = int(arg) if arg.strip().isdigit() else 10
        for descriptor, summary in self.bridge.uxas.get_recent(n):
            print(f"  {descriptor:50s} -> {summary}")

    def do_quit(self, arg: str) -> bool:
        """Exit the bridge CLI."""
        return True

    do_exit = do_quit
    do_EOF = do_quit

    def _parse_points_and_alt(self, arg: str, min_points: int):
        parts = arg.split()
        pts: list[tuple[float, float]] = []
        alt = 50.0
        for p in parts:
            if "," in p:
                try:
                    a, b = p.split(",")
                    pts.append((float(a), float(b)))
                except ValueError:
                    pass
            else:
                try:
                    alt = float(p)
                except ValueError:
                    pass
        if len(pts) < min_points:
            print(f"need at least {min_points} 'lat,lon' points")
            return None, None
        return pts, alt


