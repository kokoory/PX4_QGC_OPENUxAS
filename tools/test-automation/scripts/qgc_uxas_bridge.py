    # ------------------------------------------------------------------ inner

    def _next_task_id(self) -> int:
        self._task_counter += 1
        return self._task_counter

    def _next_request_id(self) -> int:
        self._request_counter += 1
        return self._request_counter

    def _state_publish_loop(self) -> None:
        interval = 1.0 / self.state_rate_hz
        while self._running:
            try:
                state = self.mavlink.get_state()
                if state.timestamp_ms == 0:
                    time.sleep(interval)
                    continue
                avs = build_air_vehicle_state(state)
                self.uxas.publish(avs)
            except Exception as exc:
                print(f"[Bridge] State publish error: {exc}")
            time.sleep(interval)

    def _handle_uxas_message(self, env: Envelope, obj: Any) -> None:
        if obj is None:
            return
        cls_name = type(obj).__name__
        if cls_name == "MissionCommand":
            self._handle_mission_command(obj)
        elif cls_name == "AutomationResponse":
            # UxAS delivers the planned route(s) INSIDE the AutomationResponse
            # (MissionCommandList) — it does not also broadcast standalone
            # MissionCommand messages in this configuration. Extract and route
            # each embedded MissionCommand the same way as a standalone one.
            mcs = getattr(obj, "MissionCommandList", None) or []
            print(f"[Bridge] Received AutomationResponse from UxAS "
                  f"({len(mcs)} MissionCommand(s))")
            for mc in mcs:
                if mc is not None:
                    self._handle_mission_command(mc)
        else:
            # Quiet by default; log unfamiliar messages at debug level
            pass

    def _handle_mission_command(self, mc) -> None:
        target_id = 0
        try:
            target_id = mc.get_VehicleID()
        except Exception:
            pass
        if target_id and target_id != self.vehicle_id:
            return  # not for us

        wps = waypoints_from_mission_command(mc)
        if not wps:
            print("[Bridge] MissionCommand had no waypoints")
            return

        s = self.mavlink.get_state()
        if s.alt_agl_m < self._alt_takeover_agl_m or not s.armed:
            with self._mission_lock:
                self._pending_mission_command = mc
            print(f"[Bridge] MissionCommand cached "
                  f"(waiting for armed && alt_agl >= "
                  f"{self._alt_takeover_agl_m:.0f} m, current "
                  f"armed={s.armed} agl={s.alt_agl_m:.1f} m)")
            return

        self._activate_mission(mc)

    def _activate_mission(self, mc) -> None:
        wps = waypoints_from_mission_command(mc)
        # Yaw each waypoint along the direction of travel so the airframe (and
        # a heading-mounted camera) points where it is going. PX4 adopts the
        # ACTIVE waypoint's param4 while flying the leg INTO it, so waypoint N
        # must carry the bearing of the incoming leg (N-1 → N), not the
        # outgoing one. The first waypoint has no incoming leg, so it borrows
        # the first outgoing bearing.
        items = []
        for i, wp in enumerate(wps):
            prev = wps[i - 1] if i > 0 else None
            if prev is not None:
                yaw_deg = _bearing_deg(prev.lat_deg, prev.lon_deg,
                                       wp.lat_deg, wp.lon_deg)
            elif len(wps) > 1:
                yaw_deg = _bearing_deg(wp.lat_deg, wp.lon_deg,
                                       wps[1].lat_deg, wps[1].lon_deg)
            else:
                yaw_deg = 0.0
            items.append({
                "frame": 6,  # MAV_FRAME_GLOBAL_RELATIVE_ALT_INT
                "command": 16,  # MAV_CMD_NAV_WAYPOINT
                "autocontinue": 1, "param1": 0, "param2": 5.0,
                "param3": 0, "param4": yaw_deg,
                "lat": wp.lat_deg, "lon": wp.lon_deg, "alt": wp.alt_m,
            })
        # PX4 fixed-wing rejects AUTO.MISSION without a landing (MIS_TKO_LAND_REQ).
        # Append a NAV_LAND at the last search waypoint so the mission is valid
        # for both fixed-wing and multicopter (a rough "land where you finished").
        if items:
            last = items[-1]
            alt_L = max(50.0, float(last.get("alt", 0.0)))
            # Bearing of the final leg (so the touchdown extends straight ahead).
            if len(items) >= 2:
                brg = _bearing_deg(items[-2]["lat"], items[-2]["lon"],
                                   last["lat"], last["lon"])
            else:
                brg = 0.0
            # Push the touchdown point downrange for a gentle ~6° glide; PX4's
            # fixed-wing landing rejects approaches steeper than ~8°, so placing
            # NAV_LAND at the last waypoint (near-vertical descent) is refused.
            glide_d = max(500.0, alt_L / math.tan(math.radians(6.0)))
            brg_rad = math.radians(brg)
            lat_land = last["lat"] + _meters_to_lat(glide_d * math.cos(brg_rad))
            lon_land = last["lon"] + _meters_to_lon(glide_d * math.sin(brg_rad),
                                                    last["lat"])
            items.append({
                "frame": 6,  # MAV_FRAME_GLOBAL_RELATIVE_ALT_INT
                "command": 21,  # MAV_CMD_NAV_LAND
                "autocontinue": 1, "param1": 0, "param2": 0,
                "param3": 0, "param4": float('nan'),
                "lat": lat_land, "lon": lon_land, "alt": 0,
            })
        print(f"[Bridge] Activating UxAS mission ({len(items)} waypoints, "
              f"incl. landing) on vehicle {self.vehicle_id}")
        # Dump the converted mission for offline analysis (issue: vehicle
        # entered AUTO.MISSION but immediately reported COMPLETE/LOITER).
        try:
            dump_dir = os.path.join(_SCRIPT_DIR, "..", "logs")
            os.makedirs(dump_dir, exist_ok=True)
            dump_path = os.path.join(
                dump_dir, f"mission_dump_v{self.vehicle_id}_"
                          f"{int(time.time())}.json")
            with open(dump_path, "w") as fh:
                json.dump({
                    "vehicle_id": self.vehicle_id,
                    "first_waypoint": getattr(mc, "get_FirstWaypoint",
                                              lambda: None)(),
                    "waypoint_numbers": [
                        wp.get_Number() for wp in mc.get_WaypointList()],
                    "next_waypoints": [
                        wp.get_NextWaypoint() for wp in mc.get_WaypointList()],
                    "items": items,
                }, fh, indent=1)
            print(f"[Bridge] Mission dumped to {dump_path}")
            for it in items[:3] + items[-2:]:
                print(f"[Bridge]   wp ({it['lat']:.6f},{it['lon']:.6f}) "
                      f"alt={it['alt']:.1f}")
        except Exception as exc:
            print(f"[Bridge] Mission dump failed: {exc}")
        ok = self.mavlink.upload_mission(items)
        if not ok:
            print(f"[Bridge] Failed to upload mission to vehicle "
                  f"{self.vehicle_id}")
            return
        if self.mavlink.set_mode_auto_mission():
            # Defense in depth: verify the mode actually stuck. If PX4
            # bounced back to LOITER (e.g. mode change raced another auto
            # mode), re-command once — a second activation resets the
            # navigator's finished flag and the mission executes normally.
            for _ in range(5):
                time.sleep(1.0)
                if self.mavlink.get_state().mode == "auto_mission":
                    break
            else:
                print(f"[Bridge] AUTO.MISSION did not stick "
                      f"(mode={self.mavlink.get_state().mode}) — re-commanding")
                self.mavlink.set_mode_auto_mission()
            self._mission_active = True
            print(f"[Bridge] Vehicle {self.vehicle_id} entered AUTO.MISSION")

    def _takeover_loop(self) -> None:
        """Monitor altitude + arm state; auto-arm air-spawn vehicles and
        activate cached UxAS missions once the vehicle is high enough."""
        announced_ready = False
        while self._running:
            time.sleep(1.0)
            s = self.mavlink.get_state()

            # Auto-arm (air-spawn fixed-wing)
            if (self._auto_arm and not self._auto_armed and not s.armed
                    and s.alt_agl_m >= self._auto_arm_min_alt
                    and s.gps_fix >= 3):
                print(f"[Bridge] Auto-arm: agl={s.alt_agl_m:.1f}m gps_fix={s.gps_fix}")
                if self.mavlink.arm(True):
                    self._auto_armed = True
                    # Cessna needs cruise stabilization first → wait a bit then
                    # switch to AUTO.MISSION so the existing throttle ramp
                    # doesn't fight a fresh mode change.
                    threading.Thread(
                        target=self._delayed_auto_mission,
                        args=(3.0,), daemon=True).start()

            # Auto-takeoff (ground-spawn multicopter)
            if (self._auto_takeoff_agl_m > 0 and not self._takeoff_initiated
                    and not s.armed and s.gps_fix >= 3
                    and s.alt_agl_m < 5.0):
                print(f"[Bridge] Auto-takeoff sequence: arm + TAKEOFF to "
                      f"{self._auto_takeoff_agl_m:.0f}m AGL")
                if self.mavlink.arm(True):
                    time.sleep(1.0)
                    if self.mavlink.takeoff(self._auto_takeoff_agl_m):
                        self._takeoff_initiated = True
                    else:
                        # Roll back arm so we can retry next iteration
                        self.mavlink.arm(False)

            # Activate cached mission when ready.
            # NOTE: must NOT activate while AUTO.TAKEOFF is still running.
            # The takeover altitude (200 m) is below the takeoff target
            # (220 m), so the threshold always crosses mid-takeoff; switching
            # to AUTO.MISSION at that moment makes the PX4 navigator mark the
            # fresh mission finished without flying it (mission_result
            # finished=True, seq_reached=-1) and fall back to AUTO.LOITER.
            # Waiting for the takeoff mode to end fixes the race.
            with self._mission_lock:
                pending = self._pending_mission_command
            if pending is not None and s.armed \
                    and s.alt_agl_m >= self._alt_takeover_agl_m \
                    and s.mode != "auto_takeoff":
                with self._mission_lock:
                    self._pending_mission_command = None
                print(f"[Bridge] Vehicle {self.vehicle_id} reached "
                      f"{s.alt_agl_m:.1f} m AGL — activating UxAS mission")
                self._activate_mission(pending)
            elif pending is not None and not announced_ready and s.armed:
                announced_ready = True
                print(f"[Bridge] Vehicle {self.vehicle_id} armed, climb to "
                      f"{self._alt_takeover_agl_m:.0f} m AGL to trigger "
                      f"UxAS mission")

    def _delayed_auto_mission(self, delay_s: float) -> None:
        time.sleep(delay_s)
        if self._running:
            self.mavlink.set_mode_auto_mission()


