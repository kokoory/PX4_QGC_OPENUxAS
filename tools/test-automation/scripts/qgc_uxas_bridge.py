class UxASInterface:
    """Talks to OpenUxAS LmcpObjectNetworkPublishPullBridge.

    UxAS exposes an external PUB socket (we SUB to it) and an external PULL
    socket (we PUSH to it). Each datagram is an AddressedAttributedMessage
    single-part envelope wrapping an LMCP binary payload.
    """

    def __init__(self, sub_addr: str, push_addr: str,
                 entity_id: int, service_id: int = 0,
                 source_group: str = "",
                 monitor: Optional["MonitorTap"] = None):
        self.sub_addr = sub_addr
        self.push_addr = push_addr
        self.entity_id_str = str(entity_id)
        self.service_id_str = str(service_id)
        self.source_group = source_group
        self.monitor = monitor

        self.ctx: Optional[zmq.Context] = None
        self.sub_socket: Optional[zmq.Socket] = None
        self.push_socket: Optional[zmq.Socket] = None
        self._running = False
        self._thread: Optional[threading.Thread] = None
        self._lock = threading.Lock()
        self._callbacks: list[Callable[[Envelope, Any], None]] = []
        self._recent_messages: list[tuple[str, str]] = []  # (descriptor, summary)
        self._factory = LMCPFactory.LMCPFactory()
        self.stats = BridgeStats()

    def start(self) -> None:
        self.ctx = zmq.Context.instance()

        self.sub_socket = self.ctx.socket(zmq.SUB)
        self.sub_socket.connect(self.sub_addr)
        self.sub_socket.setsockopt_string(zmq.SUBSCRIBE, "")
        print(f"[UxAS] SUB connected to {self.sub_addr} "
              f"(receives from UxAS PUB)")

        self.push_socket = self.ctx.socket(zmq.PUSH)
        self.push_socket.connect(self.push_addr)
        print(f"[UxAS] PUSH connected to {self.push_addr} "
              f"(sends into UxAS PULL)")

        self._running = True
        self._thread = threading.Thread(target=self._receive_loop, daemon=True,
                                        name="uxas-receiver")
        self._thread.start()

    def stop(self) -> None:
        self._running = False
        if self._thread:
            self._thread.join(timeout=3)
        for sock in (self.sub_socket, self.push_socket):
            if sock is not None:
                try:
                    sock.close(linger=0)
                except Exception:
                    pass

    def publish(self, lmcp_obj) -> None:
        """Pack an LMCP object into binary, wrap in envelope, push to UxAS."""
        if self.push_socket is None:
            print("[UxAS] PUSH socket not connected -- drop message")
            return
        descriptor = lmcp_obj.FULL_LMCP_TYPE_NAME
        # CMASI broadcast pattern: address == descriptor
        payload = bytes(LMCPFactory.packMessage(lmcp_obj, True))
        envelope = encode_envelope(
            address=descriptor,
            descriptor=descriptor,
            source_group=self.source_group,
            entity_id=self.entity_id_str,
            service_id=self.service_id_str,
            payload=payload,
        )
        self.push_socket.send(envelope)
        with self._lock:
            self.stats.lmcp_msgs_out += 1
        if self.monitor is not None:
            self.monitor.emit("uxas_out",
                              type(lmcp_obj).__name__,
                              _summarise_lmcp(lmcp_obj),
                              extra={"descriptor": descriptor})

    def on_message(self, callback: Callable[[Envelope, Any], None]) -> None:
        """Register a callback (envelope, decoded_lmcp_obj_or_None)."""
        self._callbacks.append(callback)

    def get_recent(self, n: int = 10) -> list[tuple[str, str]]:
        with self._lock:
            return list(self._recent_messages[-n:])

    def _receive_loop(self) -> None:
        poller = zmq.Poller()
        poller.register(self.sub_socket, zmq.POLLIN)
        while self._running:
            try:
                socks = dict(poller.poll(timeout=500))
                if self.sub_socket in socks:
                    raw = self.sub_socket.recv()
                    env = decode_envelope(raw)
                    if env is None:
                        continue
                    obj = None
                    try:
                        if env.payload:
                            obj = self._factory.getObject(bytearray(env.payload))
                    except Exception as exc:
                        print(f"[UxAS] LMCP decode error for "
                              f"{env.descriptor}: {exc}")
                    with self._lock:
                        self.stats.lmcp_msgs_in += 1
                        summary = type(obj).__name__ if obj is not None \
                            else "(undecoded)"
                        self._recent_messages.append((env.descriptor, summary))
                        if len(self._recent_messages) > 200:
                            self._recent_messages = \
                                self._recent_messages[-200:]
                    if self.monitor is not None:
                        self.monitor.emit("uxas_in",
                                          type(obj).__name__ if obj is not None
                                                              else "(undecoded)",
                                          _summarise_lmcp(obj) if obj is not None
                                                              else env.descriptor,
                                          extra={"descriptor": env.descriptor})
                    for cb in self._callbacks:
                        try:
                            cb(env, obj)
                        except Exception as exc:
                            print(f"[UxAS] Callback error: {exc}")
            except zmq.ZMQError:
                if self._running:
                    time.sleep(0.1)
            except Exception as exc:
                if self._running:
                    print(f"[UxAS] Receive error: {exc}")
                    time.sleep(0.5)


