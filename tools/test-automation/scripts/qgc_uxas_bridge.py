# Camera horizontal FOV (deg) used in the streamed AirVehicleState — UxAS reads
# this to size the sensor footprint and thus the AreaSearch lane spacing. Kept in
# sync with the QGC panel's Sensor/FOV via a shared file the search listener
# writes (uxas_search_listener writes the published "fov" to _FOV_FILE). We read
# it here rather than binding the EventBroadcaster port — binding 45678 in every
# bridge would steal publishes from the listener (SO_REUSEPORT load-balancing).
_CAMERA_FOV = [45.0]
_FOV_FILE = "/tmp/uxas_camera_fov.txt"


def _camera_fov_now(vid=None) -> float:
    """Current camera FOV (deg) for the streamed AirVehicleState. Prefers a
    per-vehicle file (/tmp/uxas_camera_fov_<vid>.txt — written by SAR tasking so
    fixed-wing and multicopter can use different FOVs), then the shared file, then
    the bridge's --camera-fov default."""
    paths = []
    if vid is not None:
        paths.append(f"/tmp/uxas_camera_fov_{vid}.txt")
    paths.append(_FOV_FILE)
    for p in paths:
        try:
            with open(p) as fh:
                fov = float(fh.read().strip())
            if 1.0 <= fov <= 120.0:
                return fov
        except (OSError, ValueError):
            continue
    return _CAMERA_FOV[0]


def _bearing_deg(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Initial great-circle bearing from point 1 to point 2, degrees 0..360
    (0 = North, 90 = East). Used to yaw a waypoint toward the next one."""
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    dlon = math.radians(lon2 - lon1)
    y = math.sin(dlon) * math.cos(phi2)
    x = (math.cos(phi1) * math.sin(phi2)
         - math.sin(phi1) * math.cos(phi2) * math.cos(dlon))
    return (math.degrees(math.atan2(y, x)) + 360.0) % 360.0


def _meters_to_lat(m: float) -> float:
    """Approximate meters → degrees of latitude (constant)."""
    return m / 111320.0


def _meters_to_lon(m: float, lat_deg: float) -> float:
    """Approximate meters → degrees of longitude at the given latitude."""
    import math
    return m / (111320.0 * max(math.cos(math.radians(lat_deg)), 1e-6))


def build_keep_in_zone(
    zone_id: int,
    center_lat: float,
    center_lon: float,
    half_size_m: float = 2000.0,
    min_alt_m: float = 0.0,
    max_alt_m: float = 500.0,
    label: str = "KeepIn",
) -> KeepInZone:
    """Build a rectangular KeepInZone centered on (lat, lon).

    The zone is a 4-vertex Polygon spanning ±half_size_m east/west and
    north/south of the center, with altitude band [min_alt_m, max_alt_m]
    (MSL).
    """
    dlat = _meters_to_lat(half_size_m)
    dlon = _meters_to_lon(half_size_m, center_lat)
    poly = Polygon()
    for lat, lon in [(center_lat - dlat, center_lon - dlon),
                     (center_lat - dlat, center_lon + dlon),
                     (center_lat + dlat, center_lon + dlon),
                     (center_lat + dlat, center_lon - dlon)]:
        poly.BoundaryPoints.append(_location3d(lat, lon, max_alt_m))

    z = KeepInZone()
    z.set_ZoneID(zone_id)
    z.set_Label(label)
    z.set_MinAltitude(min_alt_m)
    z.set_MinAltitudeType(AltitudeType.MSL)
    z.set_MaxAltitude(max_alt_m)
    z.set_MaxAltitudeType(AltitudeType.MSL)
    z.set_Boundary(poly)
    return z


def build_operating_region(
    region_id: int,
    keep_in_ids: list[int],
    keep_out_ids: Optional[list[int]] = None,
) -> OperatingRegion:
    """Build an OperatingRegion referencing existing KeepIn/KeepOut Zone IDs."""
    region = OperatingRegion()
    region.set_ID(region_id)
    for zid in keep_in_ids:
        region.KeepInAreas.append(zid)
    for zid in (keep_out_ids or []):
        region.KeepOutAreas.append(zid)
    return region


def waypoints_from_mission_command(mc) -> list[WaypointItem]:
    """Extract waypoints from an LMCP MissionCommand object."""
    items: list[WaypointItem] = []
    for i, wp in enumerate(mc.get_WaypointList()):
        try:
            turn = str(wp.get_TurnType())
        except Exception:
            turn = "TurnShort"
        items.append(WaypointItem(
            seq=i,
            lat_deg=wp.get_Latitude(),
            lon_deg=wp.get_Longitude(),
            alt_m=wp.get_Altitude(),
            speed_mps=wp.get_Speed(),
            turn_type=turn,
        ))
    return items


