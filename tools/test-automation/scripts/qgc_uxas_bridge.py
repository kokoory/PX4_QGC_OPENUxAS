class MAVLinkReader:
    """Reads MAVLink messages and updates vehicle state.

    The single mavutil connection is shared by the telemetry _read_loop and
    by upload_mission()/arm()/set_mode(). When a control method needs to
    receive specific protocol messages (MISSION_REQUEST, COMMAND_ACK, ...),
    it sets ``_capture_types`` and the _read_loop routes matching frames into
    ``_capture_queue`` instead of consuming them. Otherwise we hit the classic
    pymavlink race: both threads call recv() on the same socket and one
    silently drops the protocol replies.
    """

    def __init__(self, connection_str: str, vehicle_id: int = 1,
                 require_heartbeat: bool = True):
        self.connection_str = connection_str
        self.vehicle_id = vehicle_id
        self._require_heartbeat = require_heartbeat
        self.conn: Optional[Any] = None
        self.state = VehicleState(vehicle_id=vehicle_id)
        self._lock = threading.Lock()
        self._running = False
        self._thread: Optional[threading.Thread] = None
        self.stats = BridgeStats()
        self._capture_types: set[str] = set()
        self._capture_queue: "collections.deque[Any]" = collections.deque(maxlen=64)
        self._capture_lock = threading.Lock()
        self._control_lock = threading.Lock()  # serializes arm/set_mode/upload
        self._hb_thread: Optional[threading.Thread] = None
        self._last_mission_current: tuple = ()

    def start(self) -> None:
        print(f"[MAVLink] Connecting to {self.connection_str} ...")
        self.conn = mavutil.mavlink_connection(self.connection_str)
        if self._require_heartbeat:
            self.conn.wait_heartbeat(timeout=30)
            print(f"[MAVLink] Heartbeat received "
                  f"(system {self.conn.target_system}, "
                  f"component {self.conn.target_component})")
        else:
            print("[MAVLink] Skipping heartbeat wait (offline test mode)")
        self._running = True
        self._thread = threading.Thread(target=self._read_loop, daemon=True,
                                        name="mavlink-reader")
        self._thread.start()
        # PX4 refuses to arm ("Resolve system health failures first") until it
        # sees a GCS heartbeat on the link. Send one at 1 Hz so the bridge is
        # recognized as a connected GCS.
        self._hb_thread = threading.Thread(target=self._heartbeat_loop,
                                           daemon=True, name="gcs-heartbeat")
        self._hb_thread.start()

    def _heartbeat_loop(self) -> None:
        while self._running:
            try:
                if self.conn:
                    # MAV_TYPE_GCS=6, MAV_AUTOPILOT_INVALID=8
                    self.conn.mav.heartbeat_send(6, 8, 0, 0, 0)
            except Exception:
                pass
            time.sleep(1.0)

    def stop(self) -> None:
        self._running = False
        if self._thread:
            self._thread.join(timeout=3)
        if self._hb_thread:
            self._hb_thread.join(timeout=3)
        if self.conn:
            try:
                self.conn.close()
            except Exception:
                pass

    def get_state(self) -> VehicleState:
        with self._lock:
            return copy.copy(self.state)

    # -- capture helpers ------------------------------------------------------

    def _wait_capture(self, types: list[str], timeout: float) -> Optional[Any]:
        """Wait for a message of one of *types* that _read_loop captured."""
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            with self._capture_lock:
                for idx, msg in enumerate(self._capture_queue):
                    if msg.get_type() in types:
                        del self._capture_queue[idx]
                        return msg
            time.sleep(0.02)
        return None

    def _start_capture(self, types: list[str]) -> None:
        with self._capture_lock:
            self._capture_types = set(types)
            self._capture_queue.clear()

    def _stop_capture(self) -> None:
        with self._capture_lock:
            self._capture_types = set()
            self._capture_queue.clear()

    # -- control commands -----------------------------------------------------

    def upload_mission(self, items: list[dict]) -> bool:
        if not self.conn:
            return False
        print(f"[MAVLink] Uploading {len(items)} mission items ...")
        with self._control_lock:
            self._start_capture(["MISSION_REQUEST", "MISSION_REQUEST_INT",
                                 "MISSION_ACK"])
            try:
                self.conn.waypoint_clear_all_send()
                time.sleep(0.3)
                # Drain stray pre-handshake ACK if any.
                _ = self._wait_capture(["MISSION_ACK"], 0.2)
                self.conn.waypoint_count_send(len(items))

                for i in range(len(items)):
                    msg = self._wait_capture(
                        ["MISSION_REQUEST", "MISSION_REQUEST_INT"], 10.0)
                    if msg is None:
                        print(f"[MAVLink] Timeout waiting for "
                              f"MISSION_REQUEST (item {i})")
                        self.stats.errors += 1
                        return False
                    item = items[msg.seq] if msg.seq < len(items) else items[i]
                    self.conn.mav.mission_item_int_send(
                        self.conn.target_system,
                        self.conn.target_component,
                        msg.seq,
                        item.get("frame", 6),
                        item.get("command", 16),
                        1 if msg.seq == 0 else 0,
                        int(item.get("autocontinue", 1)),
                        item.get("param1", 0),
                        item.get("param2", 5.0),
                        item.get("param3", 0),
                        item.get("param4", 0),
                        int(item["lat"] * 1e7),
                        int(item["lon"] * 1e7),
                        item.get("alt", 50),
                    )

                ack = self._wait_capture(["MISSION_ACK"], 10.0)
                if ack and ack.type == 0:
                    self.stats.missions_uploaded += 1
                    self.stats.mavlink_msgs_out += len(items)
                    print("[MAVLink] Mission upload complete")
                    return True
                print(f"[MAVLink] Mission upload failed (ack={ack})")
                self.stats.errors += 1
                return False
            finally:
                self._stop_capture()

    def arm(self, arm_flag: bool = True, force: bool = False,
            timeout: float = 5.0) -> bool:
        """Send MAV_CMD_COMPONENT_ARM_DISARM and wait for COMMAND_ACK."""
        if not self.conn:
            return False
        param1 = 1.0 if arm_flag else 0.0
        param2 = 21196.0 if force else 0.0  # PX4 magic-number force flag
        with self._control_lock:
            self._start_capture(["COMMAND_ACK"])
            try:
                self.conn.mav.command_long_send(
                    self.conn.target_system, self.conn.target_component,
                    400,  # MAV_CMD_COMPONENT_ARM_DISARM
                    0,
                    param1, param2, 0, 0, 0, 0, 0)
                deadline = time.monotonic() + timeout
                while time.monotonic() < deadline:
                    ack = self._wait_capture(["COMMAND_ACK"], 0.5)
                    if ack is None:
                        continue
                    if ack.command == 400:
                        ok = (ack.result == 0)
                        print(f"[MAVLink] ARM={arm_flag} ack result={ack.result}"
                              f" ({'OK' if ok else 'FAIL'})")
                        return ok
            finally:
                self._stop_capture()
        return False

    def takeoff(self, target_alt_agl_m: float, timeout: float = 5.0) -> bool:
        """Send MAV_CMD_NAV_TAKEOFF to climb *target_alt_agl_m* metres AGL.

        IMPORTANT: PX4 interprets command_long NAV_TAKEOFF param7 as an
        ABSOLUTE AMSL altitude, not AGL. We convert by adding the home AMSL
        altitude derived from the current state (alt_m is AMSL, alt_agl_m is
        relative), so the vehicle actually climbs the requested AGL amount.
        PX4 auto-switches to AUTO.TAKEOFF on receipt.
        """
        if not self.conn:
            return False
        s = self.get_state()
        home_amsl = s.alt_m - s.alt_agl_m   # ground AMSL
        target_amsl = home_amsl + target_alt_agl_m
        # CRITICAL: lat/lon MUST be the current position. Sending 0,0 makes PX4
        # plan a takeoff toward the equator (0,0) — the controller then refuses
        # to spin the motors and the vehicle auto-disarms without lifting.
        cur_lat = s.lat_deg
        cur_lon = s.lon_deg
        with self._control_lock:
            self._start_capture(["COMMAND_ACK"])
            try:
                print(f"[MAVLink] TAKEOFF target {target_alt_agl_m:.0f}m AGL "
                      f"= {target_amsl:.0f}m AMSL (home {home_amsl:.0f}m) "
                      f"@ ({cur_lat:.6f},{cur_lon:.6f})")
                self.conn.mav.command_long_send(
                    self.conn.target_system, self.conn.target_component,
                    22,  # MAV_CMD_NAV_TAKEOFF
                    0,
                    0,    # param1: minimum pitch
                    0,    # param2: empty
                    0,    # param3: empty
                    float('nan'),  # param4: yaw (NaN = keep current)
                    cur_lat, cur_lon,   # current position (NOT 0,0)
                    float(target_amsl),
                )
                deadline = time.monotonic() + timeout
                while time.monotonic() < deadline:
                    ack = self._wait_capture(["COMMAND_ACK"], 0.5)
                    if ack is None:
                        continue
                    if ack.command == 22:
                        ok = (ack.result == 0)
                        print(f"[MAVLink] TAKEOFF agl={target_alt_agl_m:.0f}m "
                              f"ack={ack.result} ({'OK' if ok else 'FAIL'})")
                        return ok
                print(f"[MAVLink] TAKEOFF timed out")
                return False
            finally:
                self._stop_capture()

    def set_param(self, name: str, value: float,
                  timeout: float = 3.0) -> bool:
        """Set a PX4 parameter via PARAM_SET and wait for the PARAM_VALUE echo.

        Needed because launch_all.sh only consumes SYS_AUTOSTART from
        vehicles.json "parameters" — everything else must be applied over
        MAVLink after boot (e.g. MIS_TKO_LAND_REQ=0 so UxAS waypoint-only
        missions pass the fixed-wing feasibility check).

        PX4 rejects PARAM_SET whose param_type does not match the parameter's
        declared type, so we PARAM_REQUEST_READ first to learn the real type
        (guessing INT32 from "10" silently fails on FLOAT params).
        """
        if not self.conn:
            return False
        with self._control_lock:
            self._start_capture(["PARAM_VALUE"])
            try:
                # 1) Learn the parameter's declared type.
                self.conn.mav.param_request_read_send(
                    self.conn.target_system, self.conn.target_component,
                    name.encode(), -1)
                ptype = None
                deadline = time.monotonic() + timeout
                while time.monotonic() < deadline:
                    msg = self._wait_capture(["PARAM_VALUE"], 0.5)
                    if msg is not None and msg.param_id == name:
                        ptype = msg.param_type
                        break
                if ptype is None:
                    print(f"[MAVLink] PARAM {name} not found (read timeout)")
                    return False
                # 2) Set with the matching type (PX4 by-value convention).
                self.conn.mav.param_set_send(
                    self.conn.target_system, self.conn.target_component,
                    name.encode(), float(value), ptype)
                deadline = time.monotonic() + timeout
                while time.monotonic() < deadline:
                    msg = self._wait_capture(["PARAM_VALUE"], 0.5)
                    if msg is not None and msg.param_id == name:
                        print(f"[MAVLink] PARAM {name} = "
                              f"{msg.param_value:g} (OK)")
                        return True
                print(f"[MAVLink] PARAM {name} set timed out")
                return False
            finally:
                self._stop_capture()

    def set_mode_auto_mission(self, timeout: float = 5.0) -> bool:
        """Switch PX4 to AUTO.MISSION (main_mode=4, sub_mode=4)."""
        if not self.conn:
            return False
        # PX4 custom mode encoding: high bits = main_mode, sub_mode
        # MAIN_MODE_AUTO=4, SUB_MODE_AUTO_MISSION=4
        custom_mode = (4 << 16) | (4 << 24)
        base_mode = 1  # MAV_MODE_FLAG_CUSTOM_MODE_ENABLED
        with self._control_lock:
            self._start_capture(["COMMAND_ACK", "HEARTBEAT"])
            try:
                self.conn.mav.command_long_send(
                    self.conn.target_system, self.conn.target_component,
                    176,  # MAV_CMD_DO_SET_MODE
                    0,
                    base_mode, 4, 4, 0, 0, 0, 0)
                deadline = time.monotonic() + timeout
                while time.monotonic() < deadline:
                    msg = self._wait_capture(["COMMAND_ACK", "HEARTBEAT"], 0.5)
                    if msg is None:
                        continue
                    if msg.get_type() == "COMMAND_ACK" and msg.command == 176:
                        ok = (msg.result == 0)
                        print(f"[MAVLink] AUTO.MISSION ack result={msg.result}"
                              f" ({'OK' if ok else 'FAIL'})")
                        return ok
                print("[MAVLink] AUTO.MISSION switch timed out")
                return False
            finally:
                self._stop_capture()

    def _read_loop(self) -> None:
        while self._running:
            try:
                msg = self.conn.recv_match(blocking=True, timeout=0.5)
                if msg is None:
                    continue
                mtype = msg.get_type()
                # Route protocol replies to whichever control method is waiting.
                with self._capture_lock:
                    if self._capture_types and mtype in self._capture_types:
                        self._capture_queue.append(msg)
                        continue
                with self._lock:
                    self.stats.mavlink_msgs_in += 1
                    if mtype == "GLOBAL_POSITION_INT":
                        self.state.lat_deg = msg.lat / 1e7
                        self.state.lon_deg = msg.lon / 1e7
                        self.state.alt_m = msg.alt / 1e3
                        self.state.alt_agl_m = msg.relative_alt / 1e3
                        self.state.heading_deg = msg.hdg / 100.0
                        self.state.climb_rate_mps = -msg.vz / 100.0
                        self.state.groundspeed_mps = math.sqrt(
                            (msg.vx / 100.0) ** 2 + (msg.vy / 100.0) ** 2)
                        self.state.timestamp_ms = int(time.time() * 1000)
                    elif mtype == "GPS_RAW_INT":
                        self.state.gps_fix = msg.fix_type
                    elif mtype == "ATTITUDE":
                        self.state.roll_deg = math.degrees(msg.roll)
                        self.state.pitch_deg = math.degrees(msg.pitch)
                        self.state.yaw_deg = math.degrees(msg.yaw)
                    elif mtype == "VFR_HUD":
                        self.state.airspeed_mps = msg.airspeed
                        self.state.groundspeed_mps = msg.groundspeed
                    elif mtype == "SYS_STATUS":
                        if msg.battery_remaining >= 0:
                            self.state.battery_pct = float(msg.battery_remaining)
                    elif mtype == "HEARTBEAT":
                        self.state.armed = bool(
                            msg.base_mode
                            & mavutil.mavlink.MAV_MODE_FLAG_SAFETY_ARMED)
                        custom = msg.custom_mode
                        main_mode = (custom >> 16) & 0xFF
                        sub_mode = (custom >> 24) & 0xFF
                        mode_map = {
                            (1, 0): "manual",
                            (2, 0): "posctl",
                            (4, 1): "auto_ready",
                            (4, 2): "auto_takeoff",
                            (4, 3): "auto_loiter",
                            (4, 4): "auto_mission",
                            (4, 5): "auto_rtl",
                            (4, 6): "auto_land",
                            (6, 0): "offboard",
                        }
                        self.state.mode = mode_map.get(
                            (main_mode, sub_mode),
                            f"custom({main_mode},{sub_mode})")
                    elif mtype == "STATUSTEXT":
                        # PX4 explains mission rejections / warnings here —
                        # essential when AUTO.MISSION silently falls back to
                        # LOITER (e.g. feasibility check failures).
                        print(f"[PX4:{self.vehicle_id}] {msg.text}")
                    elif mtype == "MISSION_CURRENT":
                        # mission_state: 1=NO_MISSION 2=NOT_STARTED 3=ACTIVE
                        #                4=PAUSED 5=COMPLETE
                        cur = (msg.seq, getattr(msg, "mission_state", 0),
                               getattr(msg, "total", 0))
                        if cur != self._last_mission_current:
                            self._last_mission_current = cur
                            print(f"[PX4:{self.vehicle_id}] MISSION_CURRENT "
                                  f"seq={cur[0]} state={cur[1]} total={cur[2]}")
            except Exception as exc:
                if self._running:
                    print(f"[MAVLink] Read error: {exc}")
                    time.sleep(0.5)


