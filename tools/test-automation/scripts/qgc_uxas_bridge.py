#!/usr/bin/env python3
"""
QGC (MAVLink) <-> OpenUxAS (LMCP/ZeroMQ) Bridge.

Wire-compatible with the OpenUxAS LmcpObjectNetworkPublishPullBridge:
    - Subscribes (ZMQ_SUB) to UxAS's external publish socket (default 5560).
    - Pushes (ZMQ_PUSH) to UxAS's external pull socket (default 5561).
    - Each datagram is an AddressedAttributedMessage single-part envelope:
        <address> '$' <contentType> '|' <descriptor> '|' <sourceGroup>
        '|' <sourceEntityId> '|' <sourceServiceId> '$' <LMCP binary payload>
      where the payload is the binary serialization produced by
      lmcp.LMCPFactory.packMessage(obj, calcChecksum=True).

The bridge:
    - Reads MAVLink telemetry from PX4/QGC and publishes AirVehicleConfiguration
      and AirVehicleState messages to UxAS at a configurable rate.
    - Receives MissionCommand from UxAS, converts each Waypoint to a MAVLink
      mission item, and uploads the mission to the vehicle.
    - Provides an interactive CLI to register vehicles and submit AreaSearchTask
      / LineSearchTask + AutomationRequest sequences.

Usage:
    python3 qgc_uxas_bridge.py --mavlink udp:127.0.0.1:14550 \\
        --uxas-pub tcp://127.0.0.1:5560 --uxas-pull tcp://127.0.0.1:5561 \\
        --vehicle-id 1 --auto-register
"""

