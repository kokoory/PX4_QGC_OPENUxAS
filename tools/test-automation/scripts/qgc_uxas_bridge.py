# ---------------------------------------------------------------------------
# AddressedAttributedMessage envelope (single-part, '$' / '|' delimiters)
# ---------------------------------------------------------------------------

ADDR_DELIM = b"$"
FIELD_DELIM = b"|"


def encode_envelope(
    address: str,
    descriptor: str,
    source_group: str,
    entity_id: str,
    service_id: str,
    payload: bytes,
    content_type: str = "lmcp",
) -> bytes:
    """Build the single-part AddressedAttributedMessage wire form."""
    addr = address.encode("utf-8")
    attrs = FIELD_DELIM.join([
        content_type.encode("utf-8"),
        descriptor.encode("utf-8"),
        source_group.encode("utf-8"),
        entity_id.encode("utf-8"),
        service_id.encode("utf-8"),
    ])
    return addr + ADDR_DELIM + attrs + ADDR_DELIM + payload


@dataclass
class Envelope:
    address: str
    content_type: str
    descriptor: str
    source_group: str
    entity_id: str
    service_id: str
    payload: bytes


def decode_envelope(data: bytes) -> Optional[Envelope]:
    """Parse the wire-form envelope. The payload is binary-safe (may contain $)."""
    idx_addr = data.find(ADDR_DELIM)
    if idx_addr < 0:
        return None
    idx_attrs = data.find(ADDR_DELIM, idx_addr + 1)
    if idx_attrs < 0:
        return None

    address = data[:idx_addr].decode("utf-8", errors="replace")
    attrs_raw = data[idx_addr + 1:idx_attrs].decode("utf-8", errors="replace")
    payload = bytes(data[idx_attrs + 1:])

    parts = attrs_raw.split("|")
    while len(parts) < 5:
        parts.append("")
    return Envelope(
        address=address,
        content_type=parts[0],
        descriptor=parts[1],
        source_group=parts[2],
        entity_id=parts[3],
        service_id=parts[4],
        payload=payload,
    )


