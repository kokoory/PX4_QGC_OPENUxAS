def main(argv: Optional[list[str]] = None) -> int:
    args = _build_parser().parse_args(argv)

    # Camera FOV default; the live value tracks the QGC panel via _FOV_FILE,
    # which the UxAS search listener writes on each publish (no port contention).
    _CAMERA_FOV[0] = args.camera_fov

    capability = {
        "min_speed": args.min_speed,
        "max_speed": args.max_speed,
        "nominal_speed": args.nominal_speed,
        "min_alt": args.min_alt,
        "max_alt": args.max_alt,
        "nominal_alt": args.nominal_alt,
        "max_climb": args.max_climb,
        "max_bank_deg": args.max_bank_deg,
    }
    bridge = QGCUxASBridge(
        mavlink_str=args.mavlink,
        uxas_pub=args.uxas_pub,
        uxas_pull=args.uxas_pull,
        vehicle_id=args.vehicle_id,
        state_rate_hz=args.state_rate,
        require_heartbeat=not args.no_heartbeat_wait,
        vehicle_label=args.label,
        capability=capability,
        alt_takeover_agl_m=args.alt_takeover_agl,
        auto_arm_on_start=args.auto_arm_on_start,
        auto_arm_min_alt_agl_m=args.auto_arm_min_alt,
        auto_takeoff_agl_m=args.auto_takeoff_agl,
        monitor_port=args.monitor_port,
        monitor_host=args.monitor_host,
    )

    def signal_handler(signum, frame):
        print(f"\n[Bridge] Signal {signum} received -- shutting down")
        bridge.stop()
        sys.exit(0)

    signal.signal(signal.SIGINT, signal_handler)
    signal.signal(signal.SIGTERM, signal_handler)

    try:
        bridge.start()
        for spec in args.px4_param:
            name, sep, raw = spec.partition("=")
            if not sep:
                print(f"[Bridge] Ignoring malformed --px4-param {spec!r}")
                continue
            try:
                value = float(raw)
            except ValueError:
                print(f"[Bridge] Ignoring non-numeric --px4-param {spec!r}")
                continue
            bridge.mavlink.set_param(name.strip(), value)
        if args.auto_register:
            time.sleep(1.0)  # let connections stabilize
            bridge.register_vehicle()

        if args.non_interactive:
            print("[Bridge] Running in non-interactive mode. Ctrl+C to stop.")
            while True:
                time.sleep(1)
        else:
            BridgeCLI(bridge).cmdloop()
    except KeyboardInterrupt:
        pass
    finally:
        bridge.stop()
    return 0


if __name__ == "__main__":
    sys.exit(main())
